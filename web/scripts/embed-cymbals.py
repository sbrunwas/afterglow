#!/usr/bin/env python3
"""Convert the pinned ER-99 WAV sources to deterministic signed PCM16 tables."""
from pathlib import Path
import wave

root = Path(__file__).resolve().parents[1] / 'src/core/third_party/ER99'
parts = ['// Generated by scripts/embed-cymbals.py. ER-99 samples: GPL-3.0.\n'
         '// See PROVENANCE.md and LICENSE. This is sampled audio, not a ROM dump.\n'
         '#pragma once\n#include <cstdint>\nnamespace ag::er99 {\n']
for name in ['hh', 'crash', 'ride']:
    with wave.open(str(root / (name + '.wav'))) as source:
        assert source.getnchannels() == 1 and source.getframerate() == 44100
        width = source.getsampwidth()
        assert width in (2, 3)
        raw = source.readframes(source.getnframes())
    values = [int.from_bytes(raw[i:i+width], 'little', signed=True) >> (8*(width-2))
              for i in range(0, len(raw), width)]
    parts.append(f'inline constexpr int16_t {name}[] = {{\n')
    parts.extend(','.join(map(str, values[i:i+24])) + ',\n' for i in range(0, len(values), 24))
    parts.append('};\n')
parts.append('}\n')
(root / 'CymbalData.h').write_text(''.join(parts))
