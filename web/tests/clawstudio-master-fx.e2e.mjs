import assert from 'node:assert/strict';import fs from 'node:fs';import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--autoplay-policy=no-user-gesture-required']});
const page=await browser.newPage({acceptDownloads:true});const errors=[];
page.on('pageerror',e=>errors.push(e.message));page.on('dialog',async d=>d.accept());
try{
 await page.goto('http://127.0.0.1:8765/clawstudio.html',{waitUntil:'networkidle',timeout:30000});
 await page.locator('#c-desktab').click();
 assert.equal(await page.locator('#cmf-grid .cmf-step').count(),16);
 assert.match(await page.locator('#cmf-power').innerText(),/BYPASSED/);
 await page.locator('#cmf-power').click();
 await page.locator('#cmf-seq').click();
 await page.locator('[data-master-brush="REVERSE"]').click();
 await page.locator('[data-master-step="2"]').click();
 assert.match(await page.locator('[data-master-step="2"]').innerText(),/REVERSE/);
 await page.locator('[data-map-target="0"]').selectOption('CRUSH');
 await page.locator('[data-map-depth="0"]').evaluate(input=>{input.value='0.65';input.dispatchEvent(new Event('input',{bubbles:true}))});
 assert.equal(await page.locator('[data-map-target="0"]').inputValue(),'CRUSH');
 await page.locator('#cs10-store').click();
 await page.locator('#cmf-power').click();
 assert.match(await page.locator('#cmf-power').innerText(),/BYPASSED/);
 await page.locator('#cs10-map [data-scene="1"]').click();
 await page.locator('#cs10-map [data-scene="0"]').click();
 assert.match(await page.locator('#cmf-power').innerText(),/MASTER FX ON/);
 assert.equal(await page.locator('[data-master-step="2"] b').innerText(),'RV');
 await page.locator('#c-play').click();
 await page.waitForFunction(()=>/ready|unavailable/i.test(document.querySelector('#cmf-status')?.textContent||''),null,{timeout:20000});
 assert.match(await page.locator('#cmf-status').innerText(),/ready/i,'Actual master AudioWorklet must load');
 const gesture=page.locator('[data-master-gesture="RETRIG"]');await gesture.hover();await page.mouse.down();
 assert.equal(await gesture.evaluate(x=>x.classList.contains('held')),true);
 await page.mouse.up();
 assert.equal(await gesture.evaluate(x=>x.classList.contains('held')),false);
 await page.locator('#cmf-bars').selectOption('1');
 await page.locator('#cmf-run').click();
 assert.match(await page.locator('#cmf-status').innerText(),/queued/i);
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#cs17-save-project').click();
 const d=await downloadPromise;const data=JSON.parse(fs.readFileSync(await d.path(),'utf8'));
 assert.equal(data.desk.masterPerformance.pattern[2],'REVERSE');
 assert.equal(data.desk.masterPerformance.maps[0].target,'CRUSH');
 assert.equal(data.desk.masterPerformance.seqEnabled,true);
 await page.locator('#c-stop').click();
 assert.deepEqual(errors,[]);
 console.log('Master FX PASS: real worklet, 16-step editing, gestures, scene recall, transition and project persistence');
}finally{await browser.close()}
